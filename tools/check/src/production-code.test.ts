import { describe, expect, it } from 'bun:test'
import { isProductionCode, productionCodeExclusions } from './production-code.ts'

const MODULE = 'example.test/product'

const goSources = new Map([
  [
    'backend/cmd/server/main.go',
    `package main\n\nimport (\n\t"fmt"\n\t"${MODULE}/backend/demo"\n)\n\nfunc main() {}\n`,
  ],
  ['backend/demo/service.go', `package demo\n\nimport "${MODULE}/backend/demo/store"\n`],
  ['backend/demo/store/store.go', 'package store\n'],
  ['backend/demo/store/models.go', '// Code generated by sqlc. DO NOT EDIT.\n\npackage store\n'],
  [
    'backend/demo/testing_contract/contract.go',
    `package testing_contract\n\nimport "${MODULE}/backend/demo"\n`,
  ],
  // テストからの import は、支援パッケージを本番コードにしない。
  [
    'backend/demo/service_test.go',
    `package demo\n\nimport "${MODULE}/backend/demo/testing_contract"\n`,
  ],
])

const exclusions = productionCodeExclusions(MODULE, goSources)

describe('isProductionCode', () => {
  it.each([
    ['backend/cmd/server/main.go', true],
    ['backend/demo/service.go', true],
    ['backend/demo/store/store.go', true],
    // 本番のエントリーポイントから到達しないパッケージは、テスト専用の支援である。
    ['backend/demo/testing_contract/contract.go', false],
    ['backend/demo/service_test.go', false],
    ['backend/demo/store/models.go', false],
    ['backend/demo/store/query.sql', false],
    ['backend/demo/testdata/input.go', false],
    // 作業ツリーにもうないパッケージは、支援と判断する根拠がないので本番コードとして扱う。
    ['backend/removed/handler.go', true],
    ['frontend/src/features/account/Page.tsx', true],
    ['frontend/src/api/core.ts', true],
    ['frontend/src/styles.css', true],
    ['frontend/src/api/core.test.ts', false],
    ['frontend/src/features/account/Page.test.tsx', false],
    ['frontend/src/test/globals.ts', false],
    ['frontend/src/routeTree.gen.ts', false],
    ['frontend/src/vite-env.d.ts', false],
    ['frontend/tests/e2e/sign-in.spec.ts', false],
    ['frontend/vite.config.ts', false],
    ['tools/check/src/runner.ts', false],
    ['docs/domain/demo/scenarios.feature.md', false],
  ])('%s → %p', (path, expected) => {
    expect(isProductionCode(path, exclusions)).toBe(expected)
  })
})
