/**
 * 文字列フィールドの長さ上限。一次情報は docs/design/application/api-guidelines.md の「文字列長の上限」で、
 * サーバの backend/shared/spec/length.go と同じ数を持つ。
 *
 * ここでの用途は、`lib/form.ts` の欄の規則に渡す上限の値であり、保証はサーバ側にある。
 * 欄の規則はサーバと同じく Unicode のコードポイントで数え、超過を欄のエラー文で示す。
 *
 * HTML の `maxLength` には使わない。`maxLength` は UTF-16 のコード単位で数えるので、
 * 基本多言語面の外にある絵文字などを含む値を、サーバが受け付けるのに上限の手前で止め、
 * 上限を超えた貼り付けを知らせずに切り詰める。
 *
 * パスワードには上限を課さない。パスワード管理ソフトから貼り付けた長い語句を拒むと、
 * 利用者は理由が分からないまま登録できなくなる。
 */
export const LENGTH = {
  /** IdMagic が採番する集約の ID と、語彙的な名前。 */
  handle: 64,
  /** 一行の名前。 */
  name: 100,
  /** 利用者に見せる表示名とメールの件名。 */
  displayName: 200,
  /** 呼び出し側の資源空間から来る識別子。 */
  externalId: 256,
  /** 数文の説明、パターン、表示テンプレート。 */
  description: 500,
  /** URL と URI。 */
  uri: 2048,
  /** CEL のような式。 */
  expression: 4096,
  /** 平文の本文。 */
  plainBody: 8000,
  /** HTML の本文。 */
  richBody: 20000,
  /** RFC 5321 が定めるメールアドレスの上限。 */
  email: 254,
  /** サインイン画面とメールの固定枠に収まる短いラベル。 */
  chromeLabel: 80,
  /** 同じ固定枠に置く補足テキスト。 */
  chromeText: 280,
} as const
