/**
 * 文字列フィールドの長さ上限。正本は docs/api-rules.md の "String length limits" で、
 * サーバの backend/shared/spec/length.go と同じ数を持つ。
 *
 * ここでの用途は入力欄の `maxLength` 属性だけであり、保証はサーバ側にある。属性は
 * 貼り付け時に静かに切り詰めるだけで、超過そのものは 422 として返る。
 *
 * なお HTML の `maxLength` が数えるのは UTF-16 のコード単位で、サーバが数える
 * Unicode コードポイントとは一致しない。基本多言語面の外にある絵文字などは 1 文字が
 * 2 単位になるため、入力欄の方が先に止まる。緩い側へずれることはないので、
 * サーバが受ける値を入力欄が拒むことはあっても、その逆は起きない。
 *
 * パスワード欄には付けない。パスワード管理ソフトから貼り付けた長い語句を黙って
 * 切り詰めると、利用者は短くなったことに気づかないまま登録してしまう。
 */
export const LENGTH = {
  /** IdMagic が採番する集約の ID と、語彙的な名前。 */
  handle: 64,
  /** 一行の名前。 */
  name: 100,
  /** 利用者に見せる表示名とメールの件名。 */
  displayName: 200,
  /** 呼び出し側の資源空間から来る識別子。 */
  externalId: 256,
  /** 数文の説明、パターン、表示テンプレート。 */
  description: 500,
  /** URL と URI。 */
  uri: 2048,
  /** CEL のような式。 */
  expression: 4096,
  /** 平文の本文。 */
  plainBody: 8000,
  /** HTML の本文。 */
  richBody: 20000,
  /** RFC 5321 が定めるメールアドレスの上限。 */
  email: 254,
  /** サインイン画面とメールの固定枠に収まる短いラベル。 */
  chromeLabel: 80,
  /** 同じ固定枠に置く補足テキスト。 */
  chromeText: 280,
} as const
